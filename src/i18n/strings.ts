export const STRINGS: Record<Lang, Strings> = { de, en };

export function detectLang(): Lang {
  const l = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  return l.startsWith('de') ? 'de' : 'en';
}
